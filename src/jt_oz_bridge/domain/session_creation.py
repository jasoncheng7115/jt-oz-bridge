"""Explicit new-Root intent and candidate; creation alone never grants execution."""

from typing import Literal, Self

from pydantic import Field, StrictInt, model_validator

from jt_oz_bridge.domain.catalog import ProjectScope
from jt_oz_bridge.domain.control import ControlModel
from jt_oz_bridge.domain.models import SessionRef
from jt_oz_bridge.domain.session_lifecycle import SessionRename


class NativePermissionRule(ControlModel):
    action: str = Field(min_length=1, max_length=8192)
    resource: str = Field(min_length=1, max_length=8192)
    effect: Literal["allow", "ask", "deny"]


class RootCreationTemplate(ControlModel):
    """Trusted project enrollment, never deserialized from a chat selection."""

    scope: ProjectScope
    native_project_id: str = Field(min_length=1, max_length=255)
    agent_id: str = Field(min_length=1, max_length=255)
    permissions: tuple[NativePermissionRule, ...] = Field(max_length=1000)


class SessionCreationIntent(ControlModel):
    """Must be committed durably before create; ID is generated by the bridge."""

    intent_id: str = Field(pattern=r"^[0-9a-f]{32}$")
    scope: ProjectScope
    native_session_id: str = Field(pattern=r"^ses_jtoz_[0-9a-f]{32}$")
    source_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    owner_epoch: str = Field(pattern=r"^[0-9a-f]{64}$")
    title: str | None = Field(default=None, max_length=512)

    @model_validator(mode="after")
    def title_is_literal(self) -> Self:
        if self.title is not None:
            SessionRename(previous_title="", target_title=self.title)
        return self


class NewSessionCandidate(ControlModel):
    """A checked creation/readback, not an original-execution or binding proof."""

    intent_id: str = Field(pattern=r"^[0-9a-f]{32}$")
    reference: SessionRef
    intent_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    session_info_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    native_created_at: StrictInt = Field(ge=0)
    owner_epoch: str = Field(pattern=r"^[0-9a-f]{64}$")
    observed_at: float = Field(ge=0, allow_inf_nan=False)
    starts_execution: Literal[False] = False
    registered_for_execution: Literal[False] = False


class CreatedRootObservation(ControlModel):
    """Fresh immutable-origin observation; no execution or binding authority."""

    format: Literal["original-created-root-observation-v1"] = "original-created-root-observation-v1"
    reference: SessionRef
    intent_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    creation_receipt_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    origin_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    owner_epoch: str = Field(pattern=r"^[0-9a-f]{64}$")
    native_created_at: StrictInt = Field(ge=0)
    observed_at: float = Field(ge=0, allow_inf_nan=False)


class CreatedRootActivation(ControlModel):
    """Owned workflow receipt, never a replacement for current Native authority."""

    format: Literal["created-root-activation-v1"] = "created-root-activation-v1"
    reference: SessionRef
    action_id: str = Field(pattern=r"^[0-9a-f-]{36}$")
    binding_id: str = Field(pattern=r"^[0-9a-f-]{36}$")
    binding_revision: StrictInt = Field(gt=0)
    intent_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    creation_receipt_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    project_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    contract_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    policy_fingerprint_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    notice_batch_id: str = Field(pattern=r"^[0-9a-f-]{36}$")
    notice_plan_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    activated_at: float = Field(ge=0, allow_inf_nan=False)
    starts_execution: Literal[False] = False
